async (page) => {
  const checks=[];
  const ok=(name,actual)=>{checks.push({name,pass:!!actual});if(!actual)throw new Error(name)};
  const rows=page.locator('.feedback-row');
  ok('initial 50',await rows.count()===50);
  ok('first previous disabled',await page.getByRole('button',{name:'上一页',exact:true}).isDisabled());
  const ids1=await rows.locator('.feedback-id').allTextContents();
  await page.getByRole('button',{name:'下一页',exact:true}).click();
  await page.getByText('第 2 页',{exact:true}).waitFor();
  const ids2=await rows.locator('.feedback-id').allTextContents();
  ok('second 50 distinct',ids2.length===50 && !ids2.some(id=>ids1.includes(id)));
  await page.getByRole('button',{name:'上一页',exact:true}).click();
  await page.getByText('第 1 页',{exact:true}).waitFor();
  ok('previous returns exact first page',JSON.stringify(await rows.locator('.feedback-id').allTextContents())===JSON.stringify(ids1));
  await page.getByRole('textbox',{name:'搜索',exact:true}).fill('NEEDLE-cross-page');
  await page.getByText('1 条 · 当前页 1 条',{exact:true}).waitFor();
  ok('off-page search',await rows.first().innerText().then(s=>s.includes('T37-0007')));
  ok('next disabled last',await page.getByRole('button',{name:'下一页',exact:true}).isDisabled());
  await page.getByRole('combobox',{name:'类型',exact:true}).selectOption('complaint');
  await page.getByRole('combobox',{name:'状态',exact:true}).selectOption('no_solution');
  await page.getByText('1 条 · 当前页 1 条',{exact:true}).waitFor();
  await page.getByRole('combobox',{name:'状态',exact:true}).selectOption('resolved');
  await page.getByText('0 条 · 当前页 0 条',{exact:true}).waitFor();
  checks.push({name:'combined server filters',pass:true});
  await page.getByRole('combobox',{name:'状态',exact:true}).selectOption('no_solution');
  await page.getByText('1 条 · 当前页 1 条',{exact:true}).waitFor();
  ok('summary excludes tail',!(await rows.first().innerText()).includes('FULL-BODY-END-7'));
  await rows.first().click();
  await page.locator('.detail-content').getByText(/FULL-BODY-END-7/).waitFor();
  checks.push({name:'authorized detail full body',pass:true});
  await page.getByRole('textbox',{name:'处理说明',exact:true}).fill('T37 browser verified synthetic processing explanation');
  await page.getByRole('button',{name:'标记已办结',exact:true}).click();
  await page.getByText('0 条 · 当前页 0 条',{exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.metric-success')?.textContent==='251' && document.querySelector('.metric-muted')?.textContent==='249');
  ok('selected detail remains after filtered row disappears',await page.locator('.detail-content').getByText(/FULL-BODY-END-7/).isVisible());
  await page.getByRole('textbox',{name:'搜索',exact:true}).fill('');
  await page.getByRole('combobox',{name:'类型',exact:true}).selectOption('all');
  await page.getByRole('combobox',{name:'状态',exact:true}).selectOption('all');
  await page.getByText('1000 条 · 当前页 50 条',{exact:true}).waitFor();
  const beforeNotice=await rows.locator('.feedback-id').allTextContents();
  ok('notice target outside page',!beforeNotice.some(s=>s.includes('T37-0007')));
  await page.getByRole('button',{name:/^通知/}).click();
  await page.getByRole('button',{name:/T37 非当前页通知/}).click();
  await page.locator('.detail-content').getByText(/FULL-BODY-END-7/).waitFor();
  ok('notification keeps page unchanged',JSON.stringify(await rows.locator('.feedback-id').allTextContents())===JSON.stringify(beforeNotice));
  ok('notification URL',new URL(page.url()).searchParams.get('feedback')==='T37-0007');
  await page.reload();
  await page.locator('.detail-content').getByText(/FULL-BODY-END-7/).waitFor();
  await page.getByText('1000 条 · 当前页 50 条',{exact:true}).waitFor();
  ok('reload deep link outside page',await rows.count()===50 && !(await rows.locator('.feedback-id').allTextContents()).some(s=>s.includes('T37-0007')));
  await page.screenshot({path:'output/playwright/T-37-admin-final.png',fullPage:true});
  return {task:'T-37',fixtureOnly:true,checks,ids1,ids2,url:page.url(),screenshot:'output/playwright/T-37-admin-final.png'};
}
